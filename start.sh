#!/bin/bash
cd "$(dirname "$0")"

if ! command -v node &> /dev/null; then
    echo "======================================================================"
    echo "  【エラー】Node.js が見つかりませんでした。"
    echo "======================================================================"
    echo "  Node.js をインストールしてください（https://nodejs.org/）。"
    echo "======================================================================"
    exit 1
fi

if [ ! -d "node_modules" ]; then
    echo "========================================================"
    echo "  [初回準備] 必要なパッケージをインストールしています..."
    echo "========================================================"
    npm install
fi

node server/start.js
