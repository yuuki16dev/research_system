#!/usr/bin/env bash
set -e

cd "$(dirname "$0")"

echo "======================================================================"
echo "  ◆ Research Studio  起動ランチャー"
echo "  アプリ本体 : Research Studio"
echo "  実行環境   : Node.js (動作要件: v18以上)"
echo "======================================================================"
echo ""

# 1. Node.js のインストール確認
if ! command -v node >/dev/null 2>&1; then
    echo "======================================================================"
    echo "  【環境エラー】Node.js が見つかりませんでした。"
    echo "======================================================================"
    echo "  Research Studio の実行には Node.js (v18以上) が必要です。"
    echo "  公式サイトから LTS 版 (v20 または v22 推奨) をインストールしてください:"
    echo "  https://nodejs.org/"
    echo "======================================================================"
    exit 1
fi

# 2. Node.js のバージョン確認 (Node.js 18以上が必要)
if ! node -e "if (parseInt(process.versions.node) < 18) process.exit(1)" 2>/dev/null; then
    echo "======================================================================"
    echo "  【環境エラー】Node.js のバージョンが要件を満たしていません。"
    echo "======================================================================"
    echo "  ・アプリ本体 : Research Studio"
    echo "  ・必要環境   : Node.js (バージョン 18 以上)"
    echo -n "  ・検出環境   : "
    node -v
    echo ""
    echo "  ※「v18以上」はアプリのバージョンではなく、実行に必要な Node.js のバージョンです。"
    echo "  https://nodejs.org/ から最新の LTS 版 (v20 または v22 推奨) をインストールしてください。"
    echo "======================================================================"
    exit 1
fi

# 3. 初回起動時: node_modules が無ければ自動インストール
if [ ! -d "node_modules" ]; then
    echo "======================================================================"
    echo "  [初回セットアップ] 必要なライブラリを自動インストールしています..."
    echo "======================================================================"
    npm install
fi

# 4. サーバーマネージャー起動
node server/start.js
