-- 1. ユーザープロファイルテーブル (Supabase Auth と連動)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT,
  plan TEXT NOT NULL DEFAULT 'free', -- 'free' | 'light' | 'pro' | 'admin'
  stripe_customer_id TEXT,
  stripe_subscription_id TEXT,
  subscription_status TEXT DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- RLS (Row Level Security) 有効化
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "ユーザーは自身のプロファイルを閲覧可能"
  ON public.profiles FOR SELECT
  USING (auth.uid() = id);

CREATE POLICY "ユーザーは自身のプロファイルを更新可能"
  ON public.profiles FOR UPDATE
  USING (auth.uid() = id);

-- 新規ユーザー登録時に自動で profiles レコードを作成するトリガー
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.profiles (id, email, plan)
  VALUES (new.id, new.email, 'free')
  ON CONFLICT (id) DO NOTHING;
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- 2. 月間リサーチ利用クォータ管理テーブル
CREATE TABLE IF NOT EXISTS public.research_usage (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  year_month TEXT NOT NULL, -- 'YYYY-MM' 形式 (例: '2026-11')
  used_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE (user_id, year_month)
);

ALTER TABLE public.research_usage ENABLE ROW LEVEL SECURITY;

CREATE POLICY "ユーザーは自身の利用回数を閲覧可能"
  ON public.research_usage FOR SELECT
  USING (auth.uid() = user_id);

-- 3. ユーザー別リサーチ履歴テーブル (クラウド保存用)
CREATE TABLE IF NOT EXISTS public.user_reports (
  id TEXT PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  theme TEXT NOT NULL,
  title TEXT NOT NULL,
  purpose TEXT,
  period TEXT,
  report_json JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.user_reports ENABLE ROW LEVEL SECURITY;

CREATE POLICY "ユーザーは自身のリサーチ履歴のみ閲覧可能"
  ON public.user_reports FOR SELECT
  USING (auth.uid() = user_id);

CREATE POLICY "ユーザーは自身のリサーチ履歴を挿入可能"
  ON public.user_reports FOR INSERT
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "ユーザーは自身のリサーチ履歴を削除可能"
  ON public.user_reports FOR DELETE
  USING (auth.uid() = user_id);

-- 完了インデックス作成
CREATE INDEX IF NOT EXISTS idx_research_usage_lookup ON public.research_usage(user_id, year_month);
CREATE INDEX IF NOT EXISTS idx_user_reports_user ON public.user_reports(user_id, created_at DESC);

