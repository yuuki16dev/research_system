-- ----------------------------------------------------------------------
-- 1. profiles テーブル（Supabase Auth 連携 + プラン改ざん防止）
-- ----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT,
  plan TEXT NOT NULL DEFAULT 'free', -- 'free' | 'light' | 'pro' | 'admin'
  stripe_customer_id TEXT,
  stripe_subscription_id TEXT,
  subscription_status TEXT DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'profiles'
      AND policyname = 'ユーザーは自身のプロファイルを閲覧可能'
  ) THEN
    CREATE POLICY "ユーザーは自身のプロファイルを閲覧可能"
      ON public.profiles FOR SELECT
      USING (auth.uid() = id);
  END IF;
END $$;

-- 利用者自身による plan 改ざん防止 (20261111_lock_profile_plan.sql)
DROP POLICY IF EXISTS "ユーザーは自身のプロファイルを更新可能" ON public.profiles;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.profiles (id, email, plan)
  VALUES (new.id, new.email, 'free')
  ON CONFLICT (id) DO NOTHING;
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- ----------------------------------------------------------------------
-- 2. research_usage テーブル（月間クレジット消費管理）
-- ----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.research_usage (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  year_month TEXT NOT NULL, -- 'YYYY-MM' 形式
  used_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE (user_id, year_month)
);

COMMENT ON TABLE public.research_usage IS 'ユーザーごとの月間クレジット消費管理テーブル (C-4)';
COMMENT ON COLUMN public.research_usage.used_count IS '当月消費された累計クレジット数';

ALTER TABLE public.research_usage ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'research_usage'
      AND policyname = 'ユーザーは自身の利用回数を閲覧可能'
  ) THEN
    CREATE POLICY "ユーザーは自身の利用回数を閲覧可能"
      ON public.research_usage FOR SELECT
      USING (auth.uid() = user_id);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_research_usage_lookup ON public.research_usage(user_id, year_month);

